// Runs after `next build`: writes out/sw.js, a small service worker that pre-caches every file
// of the static export so the app opens and works offline (roadmap step 6). No library: see
// docs/decisions.md for why not Serwist.
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

/** Files not pre-cached: itself, source maps, and .woff fonts (every current browser uses the .woff2 copy). */
const SKIP = [/^sw\.js$/, /\.map$/, /\.woff$/];

/** out/ path -> the URL the browser asks for. "wallets/index.html" -> "/wallets/" (trailingSlash). */
export function toUrl(rel) {
  const p = rel.split(sep).join("/");
  if (p === "index.html") return "/";
  if (p.endsWith("/index.html")) return `/${p.slice(0, -"index.html".length)}`;
  return `/${p}`;
}

/** The worker's source. Cache-first for everything pre-cached; network for the rest. */
export function swSource(urls, version) {
  return `// Generated by scripts/build-sw.mjs. Do not edit.
const CACHE = "money-${version}";
const URLS = ${JSON.stringify(urls)};

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(URLS)));
});

// A new version waits until every tab of the old one is closed, so a running page never loses its files.
self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("money-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (e) => {
  const req = e.request;
  const url = new URL(req.url);
  if (req.method !== "GET" || url.origin !== self.location.origin) return; // e.g. Supabase goes straight to the network
  e.respondWith((async () => {
    const cache = await caches.open(CACHE);
    let path = url.pathname;
    if (req.mode === "navigate" && !path.endsWith("/") && !path.includes(".")) path += "/";
    // ignoreSearch: /transactions/?period=… and RSC "?_rsc=…" requests use the same cached file.
    const hit = await cache.match(path, { ignoreSearch: true });
    if (hit) return hit;
    try {
      return await fetch(req);
    } catch (err) {
      if (req.mode === "navigate") return (await cache.match("/")) || Response.error();
      throw err;
    }
  })());
});
`;
}

async function walk(dir) {
  const out = [];
  for (const d of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, d.name);
    if (d.isDirectory()) out.push(...(await walk(p)));
    else out.push(p);
  }
  return out;
}

/** Build out/sw.js from the files in `outDir`. Returns the number of URLs pre-cached. */
export async function buildSw(outDir) {
  const files = (await walk(outDir)).map((f) => relative(outDir, f)).filter((r) => !SKIP.some((s) => s.test(r.split(sep).join("/")))).sort();
  const hash = createHash("sha256");
  for (const f of files) hash.update(f).update(await readFile(join(outDir, f)));
  const version = hash.digest("hex").slice(0, 12); // changes whenever any file changes
  await writeFile(join(outDir, "sw.js"), swSource(files.map(toUrl), version));
  return files.length;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const n = await buildSw("out");
  console.log(`sw.js: pre-caching ${n} files`);
}
